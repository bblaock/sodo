  function createControls() {
    const header = document.querySelector("header");
    if (!header) return;

    let tools = document.querySelector(".site-tools");
    if (!tools) {
      const nav = header.querySelector("nav");
      if (!nav) return;
      tools = document.createElement("div");
      tools.className = "site-tools";
      nav.appendChild(tools);
    }

    tools.innerHTML = `
      <div class="language-control">
        <button class="site-tool-button language-trigger" type="button"
          aria-label="Choose language" aria-expanded="false" aria-haspopup="true" aria-controls="site-language-menu">
          ${icons.globe}<span class="language-code">AR</span>
        </button>
        <div class="language-menu" id="site-language-menu" role="menu">
          <button class="language-option" type="button" data-lang="ar" role="menuitem" aria-label="العربية">${flagIcons.ar}</button>
          <button class="language-option" type="button" data-lang="en" role="menuitem" aria-label="English">${flagIcons.en}</button>
          <button class="language-option" type="button" data-lang="ru" role="menuitem" aria-label="Русский">${flagIcons.ru}</button>
        </div>
      </div>
      <button class="site-tool-button theme-toggle" type="button" aria-label="Toggle theme"></button>
    `;

    const trigger = tools.querySelector(".language-trigger");
    const menu = tools.querySelector(".language-menu");
    trigger.addEventListener("click", () => {
      const willOpen = !menu.classList.contains("open");
      if (willOpen) {
        const rect = trigger.getBoundingClientRect();
        const menuWidth = Math.min(50, window.innerWidth - 16);
        const left = Math.max(8, Math.min(rect.right - menuWidth, window.innerWidth - menuWidth - 8));
        menu.style.position = "fixed";
        menu.style.top = `${rect.bottom + 9}px`;
        menu.style.left = `${left}px`;
        menu.style.right = "auto";
        menu.style.width = `${menuWidth}px`;
      }
      menu.classList.toggle("open", willOpen);
      trigger.setAttribute("aria-expanded", String(willOpen));
    });
    tools.querySelectorAll(".language-option").forEach(button => {
      button.addEventListener("click", () => {
        applyLanguage(button.dataset.lang);
        menu.classList.remove("open");
        trigger.setAttribute("aria-expanded", "false");
      });
    });
    document.addEventListener("click", event => {
      if (!tools.contains(event.target)) {
        menu.classList.remove("open");
        trigger.setAttribute("aria-expanded", "false");
      }
    });
    document.addEventListener("keydown", event => {
      if (event.key === "Escape" && menu.classList.contains("open")) {
        menu.classList.remove("open");
        trigger.setAttribute("aria-expanded", "false");
        trigger.focus();
      }
    });
    tools.querySelector(".theme-toggle").addEventListener("click", () => {
      applyTheme(document.body.classList.contains("light-mode") ? "dark" : "light");
    });
  }

